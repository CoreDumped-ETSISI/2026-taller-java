public class PrimitiveTypes {
    public static void main(String[] args) {
        int number = 3;
        char character = 'A';
        double realNumber = 1.7;

        System.out.printf("number: %d\ncharacter: %c\nrealNumber: %f\n\n",
            number,
            character,
            realNumber
        );
    }
}
